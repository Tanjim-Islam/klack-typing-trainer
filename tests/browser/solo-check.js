async (page) => {
  const baseURL = new URL(page.url()).origin;
  const evidence = baseURL.includes('localhost') ? 'output/playwright' : 'output/playwright/live';
  await page.goto(`${baseURL}/`);
  await page.evaluate(() => localStorage.removeItem('klack.v1'));
  await page.reload();
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const text = async () => (await page.locator('#typing-target').textContent()).split('Text to type: ')[1].trim();
  const stored = async () => page.evaluate(() => JSON.parse(localStorage.getItem('klack.v1')));
  const input = () => page.getByRole('textbox', { name: 'Typing test input', exact: true });
  const intro = page.getByRole('button', { name: 'Dismiss the introduction' });
  if (await intro.count()) await intro.click();
  await page.getByRole('radio', { name: 'Words', exact: true }).click();
  await page.getByRole('radio', { name: '10', exact: true }).click();
  const target = await text();
  await input().focus();
  await page.keyboard.type(target[0] === 'x' ? 'z' : 'x');
  await page.keyboard.press('Backspace');
  await page.waitForTimeout(3100);
  await page.keyboard.type(target);
  await page.getByRole('button', { name: 'Fix my mistakes', exact: true }).waitFor();
  const first = (await stored()).results[0];
  assert(first.training.missedWords.some((m) => m.word === target.split(' ')[0]), 'Corrected word was lost');
  assert(first.training.benchmark.count === 10, 'Word count was not saved');
  assert(first.incorrectChars === 0, 'Correction did not repair the displayed result');
  await page.screenshot({ path: `${evidence}/mistake-result.png`, fullPage: true });
  await page.getByRole('button', { name: 'Fix my mistakes', exact: true }).click();
  assert((await text()).includes(target.split(' ')[0]), 'Repair omitted the missed word');
  const repair = await text();
  await page.keyboard.type(repair[0]);
  await page.waitForTimeout(3100);
  await page.keyboard.type(repair.slice(1));
  await page.getByRole('button', { name: 'Next test', exact: false }).waitFor();
  assert((await stored()).results[0].training.source === 'repair', 'Repair source was lost');
  await input().focus();
  await page.keyboard.press('Tab');
  await page.keyboard.press('Enter');
  assert(await input().evaluate((el) => document.activeElement === el), 'Results restart lost focus');
  await page.keyboard.press('Escape');
  await page.getByRole('radio', { name: 'Timed', exact: true }).click();
  await page.keyboard.type((await text())[0]);
  await page.keyboard.press('Tab');
  const afterTab = await text();
  await page.keyboard.press('Enter');
  assert(afterTab === await text(), 'Tab + Enter generated a second passage');
  assert(await input().evaluate((el) => document.activeElement === el), 'Restart lost focus');
  await page.keyboard.type((await text())[0]);
  await page.keyboard.press('Enter');
  assert(afterTab !== await text(), 'Enter did not restart an active test');
  await page.keyboard.press('Shift+Tab');
  assert(await input().evaluate((el) => document.activeElement !== el), 'Shift+Tab trapped keyboard focus');
  await page.goto(`${baseURL}/drills`);
  await page.getByRole('button', { name: 'New drill', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('QA daily symbols');
  await page.getByRole('textbox', { name: 'Practice text', exact: true }).fill('This: that: then: three: things.');
  await page.getByRole('button', { name: 'Create drill', exact: true }).click();
  const card = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Yours (1)', exact: true }) });
  await card.getByRole('button', { name: 'Practise', exact: true }).click();
  const drillText = await text();
  await page.keyboard.type(drillText[0]);
  await page.waitForTimeout(3100);
  await page.keyboard.type(drillText.slice(1));
  await page.getByRole('button', { name: 'Next test', exact: false }).waitFor();
  const drillResult = (await stored()).results[0];
  assert(drillResult.training.drillId, 'Saved drill ID missing');
  await page.goto(`${baseURL}/drills`);
  await page.getByRole('button', { name: 'History for QA daily symbols', exact: true }).click();
  await page.getByRole('dialog').getByText('Current', { exact: true }).waitFor();
  await page.screenshot({ path: `${evidence}/drill-history.png`, fullPage: true });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Edit QA daily symbols', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('QA renamed symbols');
  await page.getByRole('textbox', { name: 'Practice text', exact: true }).fill('These: new: words: change: practice.');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'History for QA renamed symbols', exact: true }).click();
  await page.getByRole('dialog').getByText('Earlier version', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.goto(`${baseURL}/progress`);
  await page.getByRole('combobox', { name: 'Compare similar tests' }).click();
  await page.getByRole('option').filter({ hasText: 'Words · 10 words' }).click();
  await page.getByText('One test is not a trend', { exact: true }).waitFor();
  await page.screenshot({ path: `${evidence}/fair-progress.png`, fullPage: true });
  return { passed: ['corrected mistake recovery', 'repair drill', 'saved configuration', 'Tab + Enter', 'Enter restart', 'Shift+Tab exit', 'saved drill ID', 'history dialog', 'rename and edit history after reload', 'fair comparison filter'], results: (await stored()).results.length };
}
