async (page) => {
  const baseURL = new URL(page.url()).origin;
  const evidence = baseURL.includes('localhost') ? 'output/playwright' : 'output/playwright/live';
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  await page.goto(`${baseURL}/`);
  await page.getByRole('textbox', { name: 'Typing test input', exact: true }).waitFor({ state: 'attached' });
  await page.setViewportSize({ width: 390, height: 844 });
  const intro = page.getByRole('button', { name: 'Dismiss the introduction' });
  if (await intro.count()) await intro.click();
  await page.screenshot({ path: `${evidence}/mobile-home.png`, fullPage: true });
  const fits = () => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
  assert(await fits(), 'Home overflows on mobile');
  const input = page.getByRole('textbox', { name: 'Typing test input', exact: true });
  await input.focus();
  const text = (await page.locator('#typing-target').textContent()).split('Text to type: ')[1].trim();
  await page.keyboard.type(text.slice(0, 15));
  assert(await page.evaluate(() => document.documentElement.dataset.testFocus === 'true'), 'Focus stage missing');
  assert(await page.locator('[data-bottom-nav]').isHidden(), 'Bottom nav still visible during typing');
  const before = await page.locator('.type-surface').boundingBox();
  await page.keyboard.press('Tab');
  const after = await page.locator('.type-surface').boundingBox();
  assert(Math.abs(before.y - after.y) < 1, 'Restart moved the typing surface');
  assert(await input.evaluate((el) => el === document.activeElement), 'Mobile restart lost focus');
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'light' });
  await page.keyboard.type((await page.locator('#typing-target').textContent()).split('Text to type: ')[1][0]);
  await page.keyboard.press('Tab');
  await page.screenshot({ path: `${evidence}/mobile-focus-light.png`, fullPage: true });
  await page.keyboard.press('Escape');
  await page.goto(`${baseURL}/progress`);
  assert(await fits(), 'Progress overflows on mobile');
  await page.getByRole('combobox', { name: 'Compare similar tests' }).click();
  assert(await fits(), 'Comparison dropdown overflows on mobile');
  await page.keyboard.press('Escape');
  await page.screenshot({ path: `${evidence}/mobile-progress.png`, fullPage: true });
  await page.goto(`${baseURL}/drills`);
  assert(await fits(), 'Drill cards overflow on mobile');
  await page.getByRole('button', { name: 'History for QA renamed symbols', exact: true }).click();
  assert(await fits(), 'Drill history overflows on mobile');
  await page.screenshot({ path: `${evidence}/mobile-history.png`, fullPage: true });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'no-preference', colorScheme: 'dark' });
  return { passed: ['390px home', 'stable typing position on restart', 'keyboard focus', 'mobile navigation hidden during typing', 'reduced motion', 'light theme', 'progress and filter', 'drill cards and history dialog'] };
}
